"""Generate datasets/data_dictionary.csv and docs/DATA_DICTIONARY.md from the typed Pydantic
configuration models (inputs) and the trajectory record (outputs). --check fails if stale."""
import csv
import io
import os
import sys
from pathlib import Path

os.environ.setdefault("OPENBLAS_NUM_THREADS", "1")
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import app  # noqa: E402,F401
from app.schemas.configuration import (EconomicsConfig, GeometryConfig, HeatInput, KineticsConfig, OperatingLimits,  # noqa: E402
                                       PlantConfig, SolverConfig, ThermalConfig, VacuumConfig)

OUTPUTS = [
    ("t_s", "s", "simulation time", "PREDICTED"), ("stage", "-", "process stage", "USER-DEFINED"),
    ("P_Pa", "Pa_abs", "vessel absolute pressure", "PREDICTED"), ("P_sp_Pa", "Pa_abs", "pressure set-point", "USER-DEFINED"),
    ("argon_NL_min", "NL/min", "lift argon (normal)", "USER-DEFINED"), ("oxygen_Nm3_h", "Nm3/h", "tuyere oxygen (normal)", "USER-DEFINED"),
    ("T_bulk_K", "K", "mass-averaged steel temperature", "PREDICTED"), ("T_l_K / T_d_K / T_v_K", "K", "zone temperatures", "PREDICTED"),
    ("<el>_bulk_ppm", "ppm", "bulk composition of C,O,H,N,Al,Si,Mn,Ti,S,P,Cr,Ni,Nb,V,Cu,Mo", "SOFT-SENSED/PREDICTED"),
    ("<el>_ladle_ppm / <el>_vessel_ppm", "ppm", "zone compositions", "PREDICTED"),
    ("q_circ_t_min", "t/min", "steel circulation", "ESTIMATED"), ("mixing_time_95_s", "s", "95 % mixing time", "ESTIMATED"),
    ("vessel_depth_m", "m", "steel depth in vacuum vessel", "PREDICTED"), ("ladle_level_drop_m", "m", "ladle level drop", "PREDICTED"),
    ("r_C_<site>_mol_s", "mol/s", "decarburization rate per site", "PREDICTED"), ("K_app_1_min", "1/min", "apparent decarburization constant", "PREDICTED"),
    ("o2_abs_eff", "-", "oxygen absorption efficiency", "PREDICTED"), ("jet_*_mol_s", "mol/s", "jet oxygen partition", "PREDICTED"),
    ("offgas_<g>_Nm3_h", "Nm3/h", "exhaust flow per species", "PREDICTED"), ("x_<g>", "-", "vessel gas mole fraction", "PREDICTED"),
    ("pump_w_air_kg_h", "kg/h", "pump capacity air-equivalent at P", "PREDICTED"), ("Q_<term>_W", "W", "energy ledger rates", "PREDICTED"),
    ("E_<term>_MJ", "MJ", "cumulative energy ledger", "PREDICTED"), ("total_O_ppm", "ppm", "total oxygen (inclusion model)", "PREDICTED (low confidence)"),
    ("inclusion_bins_ppm", "ppm", "Al2O3 by size class 2.5/7.5/20/50 um", "PREDICTED (low confidence)"),
    ("superheat_K", "K", "superheat above empirical liquidus", "PREDICTED"), ("mass_balance_relative_error", "-", "worst element closure", "MODEL INTEGRITY"),
    ("energy_balance_relative_error", "-", "energy closure", "MODEL INTEGRITY"),
]


def rows():
    out = []
    groups = [("plant", PlantConfig), ("plant.geometry", GeometryConfig), ("plant.vacuum", VacuumConfig), ("plant.kinetics", KineticsConfig),
              ("plant.thermal", ThermalConfig), ("plant.limits", OperatingLimits), ("plant.economics", EconomicsConfig),
              ("heat", HeatInput), ("solver", SolverConfig)]
    for prefix, M in groups:
        for name, f in M.model_fields.items():
            ex = f.json_schema_extra or {}
            if f.annotation in (GeometryConfig, VacuumConfig, KineticsConfig, ThermalConfig, OperatingLimits, EconomicsConfig):
                continue
            lo = hi = ""
            for m in f.metadata:
                lo = getattr(m, "ge", lo) if hasattr(m, "ge") else lo
                hi = getattr(m, "le", hi) if hasattr(m, "le") else hi
            default = f.default if not callable(f.default_factory) else "(structured default)"
            out.append({"direction": "INPUT", "name": f"{prefix}.{name}", "unit": ex.get("unit", ""), "default": default, "min": lo, "max": hi,
                        "meaning": f.description or "", "change_frequency": ex.get("change_frequency", ""), "source": ex.get("source", ""),
                        "provenance_flag": ex.get("provenance", "")})
    for n, u, d, p in OUTPUTS:
        out.append({"direction": "OUTPUT", "name": n, "unit": u, "default": "", "min": "", "max": "", "meaning": d, "change_frequency": "every record",
                    "source": "physics twin", "provenance_flag": p})
    return out


def render():
    r = rows()
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=list(r[0]), lineterminator="\n")
    w.writeheader()
    w.writerows(r)
    md = ["# Data dictionary (generated by scripts/generate_data_dictionary.py - do not edit by hand)", "",
          "All demo defaults are ILLUSTRATIVE unless marked MEASURED/LAB ANALYZED. Bounds are enforced by the API (HTTP 422).", "",
          "| dir | name | unit | default | min | max | meaning | change freq. | source | flag |", "|---|---|---|---|---|---|---|---|---|---|"]
    for x in r:
        md.append("| " + " | ".join(str(x[k]).replace("|", "/") for k in x) + " |")
    return buf.getvalue(), "\n".join(md) + "\n"


def main():
    csv_txt, md = render()
    pc, pm = ROOT / "app" / "datasets" / "data_dictionary.csv", ROOT / "docs" / "DATA_DICTIONARY.md"
    if "--check" in sys.argv:
        ok = pc.exists() and pc.read_text() == csv_txt and pm.exists() and pm.read_text() == md
        print("data dictionary up to date" if ok else "data dictionary STALE - run scripts/generate_data_dictionary.py")
        sys.exit(0 if ok else 1)
    pc.write_text(csv_txt)
    pm.write_text(md)
    print(f"wrote {pc} ({len(csv_txt.splitlines())-1} rows) and {pm}")


if __name__ == "__main__":
    main()
